    fun searchFaculty(query: String): List<FacultyMember> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return allFaculty
        return allFaculty.filter {
            it.name.lowercase().contains(trimmed) ||
            it.id.toString().contains(trimmed) ||
            it.department.lowercase().contains(trimmed)
        }
    }

